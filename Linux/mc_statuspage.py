"""
mc_statuspage.py — Static public status page (index.html + status.json)
regenerated by the daemon. Holds no secret, no address and no player name
unless the owner asked for the names.
"""
import html
import json
import logging
import os
import re
import sys
import time
from datetime import datetime, timezone

BASE_DIR = os.path.dirname(os.path.abspath(__file__))
sys.path.append(BASE_DIR)

import mc_config
import mc_metrics
from mc_lang import T

DEFAULT_INTERVAL = 60
MIN_INTERVAL = 10
PAGE_FILES = ("index.html", "status.json")
CONFIG_KEYS = ("status_page_dir", "status_page_interval", "status_page_players")

_FORMATTING = re.compile(r"§.")
_UNICODE_ESCAPE = re.compile(r"\\u([0-9a-fA-F]{4})")


def read_property(dossier, key):
    try:
        with open(os.path.join(dossier, "server.properties"), encoding="utf-8-sig", errors="replace") as f:
            for line in f:
                if line.startswith(key + "="):
                    return line.split("=", 1)[1].rstrip("\r\n")
    except OSError:
        pass
    return None


def clean_motd(raw):
    text = _UNICODE_ESCAPE.sub(lambda m: chr(int(m.group(1), 16)), raw or "")
    text = text.replace("\\n", " ").replace("\n", " ")
    return " ".join(_FORMATTING.sub("", text).split())


def build_document(config, sample, show_players=False, now=None):
    dossier = config.get("dossier_serveur", "")
    motd = clean_motd(read_property(dossier, "motd") or config.get("description_serveur") or "")
    maximum = sample["players_max"]
    if maximum is None:
        try:
            maximum = int(read_property(dossier, "max-players"))
        except (TypeError, ValueError):
            maximum = None
    online = sample["players_online"]
    stamp = now if now is not None else time.time()
    doc = {
        "schema": 1,
        "name": config.get("nom_serveur") or sample["name"],
        "state": sample["state"],
        "online": sample["state"] == "running",
        "players": {"online": online if online is not None else 0, "max": maximum},
        "version": sample["version"],
        "loader": sample["loader"],
        "motd": motd,
        "updated": datetime.fromtimestamp(stamp, timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "updated_ts": int(stamp),
    }
    if show_players:
        doc["players"]["names"] = list(sample["players"])
    return doc


def render_html(doc):
    esc = html.escape
    state_label = T.get(f"sp_state_{doc['state']}", doc["state"])
    players = doc["players"]
    count = f"{players['online']}/{players['max']}" if players["max"] is not None else str(players["online"])
    version = " ".join(p for p in (doc["loader"], doc["version"]) if p) or "-"
    names = ""
    if "names" in players:
        listed = ", ".join(esc(n) for n in players["names"]) or "-"
        names = f"<div><dt>{esc(T['sp_players_list'])}</dt><dd>{listed}</dd></div>"
    motd = f'<p class="motd">{esc(doc["motd"])}</p>' if doc["motd"] else ""
    return f"""<!DOCTYPE html>
<html lang="{esc(T['sp_lang'])}">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta http-equiv="refresh" content="60">
<title>{esc(doc['name'])}</title>
<style>
:root{{color-scheme:light dark;--bg:#f6f7f9;--card:#fff;--text:#1c1f24;--muted:#5b6470;--ok:#1a7f37;--off:#a1262d;--wait:#9a6700}}
@media(prefers-color-scheme:dark){{:root{{--bg:#14171b;--card:#1d2127;--text:#e8eaed;--muted:#9aa3ad;--ok:#3fb950;--off:#f47067;--wait:#d29922}}}}
body{{margin:0;padding:16px;background:var(--bg);color:var(--text);font:16px/1.5 system-ui,sans-serif}}
main{{max-width:32rem;margin:0 auto;background:var(--card);border-radius:12px;padding:20px}}
h1{{margin:0 0 4px;font-size:1.5rem}}
.motd{{margin:0 0 16px;color:var(--muted)}}
.state{{font-weight:600}}
.state.up{{color:var(--ok)}}.state.down{{color:var(--off)}}.state.wait{{color:var(--wait)}}
dl{{margin:0}}dl div{{display:flex;justify-content:space-between;gap:12px;padding:8px 0;border-top:1px solid var(--muted)}}
dt{{color:var(--muted)}}dd{{margin:0;text-align:right;overflow-wrap:anywhere}}
footer{{margin-top:16px;color:var(--muted);font-size:.85rem}}
</style>
</head>
<body>
<main>
<h1>{esc(doc['name'])}</h1>
{motd}
<dl>
<div><dt>{esc(T['sp_state'])}</dt><dd class="state {_css_class(doc['state'])}">{esc(state_label)}</dd></div>
<div><dt>{esc(T['sp_players'])}</dt><dd>{esc(count)}</dd></div>
{names}
<div><dt>{esc(T['sp_version'])}</dt><dd>{esc(version)}</dd></div>
</dl>
<footer>{esc(T['sp_updated'])} <time datetime="{esc(doc['updated'])}">{esc(doc['updated'])}</time></footer>
</main>
</body>
</html>
"""


def _css_class(state):
    if state == "running":
        return "up"
    return "wait" if state in ("starting", "stopped", "closed") else "down"


def _write_atomic(path, text):
    tmp = f"{path}.tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        f.write(text)
    os.replace(tmp, path)


def write_page(directory, doc):
    os.makedirs(directory, exist_ok=True)
    _write_atomic(os.path.join(directory, "status.json"),
                  json.dumps(doc, ensure_ascii=False, indent=2) + "\n")
    _write_atomic(os.path.join(directory, "index.html"), render_html(doc))


def remove_page(directory):
    for name in PAGE_FILES:
        try:
            os.remove(os.path.join(directory, name))
        except OSError:
            pass


def generate(name, config, collector=None, now=None):
    """Write the page configured in `config`; returns the directory."""
    directory = config["status_page_dir"]
    sample = (collector or mc_metrics.COLLECTOR).sample(name, config)
    doc = build_document(config, sample, config.get("status_page_players", 0) == 1, now)
    write_page(directory, doc)
    return directory


class Publisher:
    """Regenerates each configured page every `status_page_interval` seconds."""

    def __init__(self, collector=None, clock=time.time):
        self.collector, self.clock = collector, clock
        self.due = {}

    def run(self, servers):
        now = self.clock()
        for name, info in servers.items():
            dossier = info.get("dossier_serveur", "")
            try:
                config = mc_config.load_config(dossier)
                if not config.get("status_page_dir"):
                    self.due.pop(name, None)
                    continue
                if now < self.due.get(name, 0):
                    continue
                config["dossier_serveur"] = dossier
                generate(name, config, self.collector, now)
                interval = max(MIN_INTERVAL, int(config.get("status_page_interval", DEFAULT_INTERVAL)))
                self.due[name] = now + interval
            except Exception as e:
                self.due[name] = now + DEFAULT_INTERVAL
                logging.warning(f"[{name}] Status page not written: {e}")
